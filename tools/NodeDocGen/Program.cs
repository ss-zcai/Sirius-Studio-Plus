using System.Text;
using Sirius.Core.Graph;
using Sirius.Core.Nodes;
using Sirius.Vision;

// Generates docs/node-reference.md from the node library itself, so the
// reference cannot drift from the code. Re-run after renaming ports:
//   dotnet run --project tools/NodeDocGen -- docs/node-reference.md

var outputPath = args.Length > 0 ? args[0] : "docs/node-reference.md";

VisionNodeLibrary.Register();

var builder = new StringBuilder();
builder.AppendLine("# Node reference");
builder.AppendLine();
builder.AppendLine("Every node in the built-in library, with its ports and parameters.");
builder.AppendLine();
builder.AppendLine("> Generated by `tools/NodeDocGen` - do not edit by hand.");
builder.AppendLine("> Regenerate with `dotnet run --project tools/NodeDocGen -- docs/node-reference.md`.");
builder.AppendLine();
builder.AppendLine("Port names are what the editor shows beside each socket, so they are");
builder.AppendLine("worth choosing for the reader: prefer a role (`Source`, `Mask`, `Result`)");
builder.AppendLine("over the data type, which the socket's shape and colour already convey.");
builder.AppendLine();
builder.AppendLine("Socket shapes: square = image, circle = everything else.");
builder.AppendLine();

var descriptors = NodeCatalog.All
    .OrderBy(d => d.Category)
    .ThenBy(d => d.DisplayName, StringComparer.CurrentCulture)
    .ToArray();

builder.AppendLine($"**{descriptors.Length} nodes** across {descriptors.Select(d => d.Category).Distinct().Count()} categories.");
builder.AppendLine();

// Contents, so a long list stays navigable.
foreach (var group in descriptors.GroupBy(d => d.Category))
{
    builder.AppendLine($"- **{Humanise(group.Key.ToString())}** — {string.Join(", ", group.Select(d => d.DisplayName))}");
}

builder.AppendLine();

foreach (var group in descriptors.GroupBy(d => d.Category))
{
    builder.AppendLine($"## {Humanise(group.Key.ToString())}");
    builder.AppendLine();

    foreach (var descriptor in group)
    {
        builder.AppendLine($"### {descriptor.DisplayName}");
        builder.AppendLine();
        builder.AppendLine($"`{descriptor.TypeKey}`");
        builder.AppendLine();

        if (!string.IsNullOrWhiteSpace(descriptor.Description))
        {
            builder.AppendLine(descriptor.Description);
            builder.AppendLine();
        }

        VisionNode instance;
        try
        {
            instance = descriptor.CreateInstance();
        }
        catch (Exception ex)
        {
            builder.AppendLine($"> Could not inspect ports: {ex.Message}");
            builder.AppendLine();
            continue;
        }

        AppendPorts(builder, "Inputs", instance.Inputs.Select(p => (p.Name, p.DataType, (bool?)p.IsRequired)));
        AppendPorts(builder, "Outputs", instance.Outputs.Select(p => (p.Name, p.DataType, (bool?)null)));

        if (descriptor.Parameters.Count > 0)
        {
            builder.AppendLine("**Parameters**");
            builder.AppendLine();
            builder.AppendLine("| Name | Type | Editor | Range |");
            builder.AppendLine("| --- | --- | --- | --- |");

            foreach (var parameter in descriptor.Parameters)
            {
                var attribute = parameter.Attribute;
                // A parameter may take its bounds from other parameters, in
                // which case the range is whatever the operator sets.
                var range = (attribute.MinSource, attribute.MaxSource) switch
                {
                    (not null, not null) => $"set by {attribute.MinSource} / {attribute.MaxSource}",
                    (not null, null) => $"from {attribute.MinSource}",
                    (null, not null) => $"up to {attribute.MaxSource}",
                    _ => attribute.HasMin && attribute.HasMax
                        ? $"{Trim(attribute.Min)} to {Trim(attribute.Max)}{(attribute.OddOnly ? ", odd only" : string.Empty)}"
                        : attribute.OddOnly ? "odd only" : "-",
                };

                builder.AppendLine(
                    $"| {parameter.DisplayName} | `{FriendlyType(parameter.ValueType)}` | {parameter.Editor} | {range} |");
            }

            builder.AppendLine();
        }
    }
}

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outputPath))!);
File.WriteAllText(outputPath, builder.ToString());
Console.WriteLine($"Wrote {outputPath} ({descriptors.Length} nodes)");

static void AppendPorts(StringBuilder builder, string heading, IEnumerable<(string Name, Type Type, bool? Required)> ports)
{
    var list = ports.ToArray();
    if (list.Length == 0)
        return;

    builder.AppendLine($"**{heading}**");
    builder.AppendLine();
    builder.AppendLine("| Port | Type | Shape | Required |");
    builder.AppendLine("| --- | --- | --- | --- |");

    foreach (var (name, type, required) in list)
    {
        var shape = type.Name == "ImageData" ? "square" : "circle";
        var requiredText = required is null ? "-" : required.Value ? "yes" : "optional";
        builder.AppendLine($"| {name} | `{FriendlyType(type)}` | {shape} | {requiredText} |");
    }

    builder.AppendLine();
}

// Shared with the shell, so the reference and the sockets cannot drift.
static string FriendlyType(Type type) => Sirius.Core.Nodes.TypeNames.Friendly(type);

static string Trim(double value) => value == Math.Floor(value) ? ((long)value).ToString() : value.ToString("0.##");

static string Humanise(string value)
{
    var builder = new StringBuilder();
    for (var i = 0; i < value.Length; i++)
    {
        if (i > 0 && char.IsUpper(value[i]))
            builder.Append(' ');
        builder.Append(value[i]);
    }

    return builder.ToString();
}
